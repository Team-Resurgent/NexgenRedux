#!/usr/bin/env python3
"""Compiles the Direct3D 11 shaders with fxc (in the Windows SDK) into one C++ header.

The header is checked in, so building the engine doesn't need this.

    python engine/tools/build_shaders.py
"""
import pathlib
import shutil
import subprocess
import tempfile

SHADERS = pathlib.Path(__file__).resolve().parent.parent / "gpu" / "d3d11" / "shaders"
# Shader model 4.0 runs on feature level 10_0 and up.
FILES = {
    "basic": [("basicVs", "vsMain", "vs_4_0"), ("basicPs", "psMain", "ps_4_0")],
    "mesh": [("meshVs", "meshVs", "vs_4_0"), ("meshPs", "meshPs", "ps_4_0"), ("shadowVs", "shadowVs", "vs_4_0"),
             ("screenVs", "screenVs", "vs_4_0"), ("skyPs", "skyPs", "ps_4_0"), ("fieldPs", "fieldPs", "ps_4_0")],
    "post": [("blurPs", "blurPs", "ps_4_0"), ("gradePs", "gradePs", "ps_4_0"), ("occlusionPs", "occlusionPs", "ps_4_0"), ("occludePs", "occludePs", "ps_4_0"),
             ("reflectPs", "reflectPs", "ps_4_0"), ("focusPs", "focusPs", "ps_4_0"), ("meterPs", "meterPs", "ps_4_0"), ("exposePs", "exposePs", "ps_4_0")],
}


def find_fxc():
    found = shutil.which("fxc")
    if found:
        return found
    kits = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\bin")
    options = sorted(kits.glob("10.*/x64/fxc.exe"))
    if not options:
        raise SystemExit("fxc not found: install the Windows SDK")
    return str(options[-1])


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return f"inline constexpr unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    fxc = find_fxc()
    for file, stages in FILES.items():
        out = [f"// Generated by tools/build_shaders.py from {file}.hlsl. Do not edit.", "#pragma once", "", "namespace nx::gpu::shaders", "{"]
        with tempfile.TemporaryDirectory() as tmp:
            for name, entry, profile in stages:
                binary = pathlib.Path(tmp) / (name + ".cso")
                subprocess.run([fxc, "/nologo", "/T", profile, "/E", entry, "/O3", "/WX", "/Qstrip_debug",
                                "/Qstrip_reflect", "/Fo", str(binary), str(SHADERS / (file + ".hlsl"))], check=True)
                out.append(array(name, binary.read_bytes()))
        out.append("}")
        target = SHADERS / (file + "_shaders.h")
        target.write_text("\n".join(out) + "\n", newline="\n")
        print("wrote", target)
    # Effects that others write are compiled with the first part of it, when they are loaded.
    text = (SHADERS / "mesh.hlsl").read_text(encoding="utf-8").replace("\r\n", "\n")
    text = text[:text.index("struct ScreenOut")].rstrip() + "\n"
    target = SHADERS / "mesh_source.h"
    target.write_text("// Generated by tools/build_shaders.py from mesh.hlsl. Do not edit.\n#pragma once\n\nnamespace nx::gpu::shaders\n{\n    inline const char kMeshSource[] = R\"(\n" + text + ")\";\n}\n", newline="\n")
    print("wrote", target)
    glsl_space()


# The effects of a view in space for OpenGL, from the same source: GLSL with the words effects use (see
# effect_source.h), its pictures read by functions that turn them the other way up.
def glsl_space():
    text = (SHADERS / "post.hlsl").read_text(encoding="utf-8").replace("\r\n", "\n")
    text = text[text.index("// --- Effects of a view in space"):]
    for declaration in ("Texture2D depthImage : register(t2);\n", "Texture2D extraImage : register(t3);\n", "SamplerState pointSampler : register(s1);\n"):
        text = text.replace(declaration, "")
    for texture, reader in (("image.SampleLevel(imageSampler, ", "readImage("), ("depthImage.SampleLevel(pointSampler, ", "readDepth("),
                            ("extraImage.SampleLevel(pointSampler, ", "readExtra(")):
        while texture in text:
            start = text.index(texture)
            depth, at = 1, start + len(texture)
            while depth:
                depth += {"(": 1, ")": -1}.get(text[at], 0)
                at += 1
            inside = text[start + len(texture):at - 1]
            text = text[:start] + reader + inside[:inside.rindex(",")] + ")" + text[at:]
    text = text.replace("[unroll] ", "").replace("[loop] ", "").replace(" : TEXCOORD0) : SV_Target", ")")
    start = """uniform sampler2D image;
uniform sampler2D depthImage;
uniform sampler2D extraImage;
layout(location = 0) out vec4 result;
in vec2 at;
vec4 readImage(vec2 p) { return textureLod(image, vec2(p.x, 1.0 - p.y), 0.0); }
vec4 readDepth(vec2 p) { return textureLod(depthImage, vec2(p.x, 1.0 - p.y), 0.0); }
vec4 readExtra(vec2 p) { return textureLod(extraImage, vec2(p.x, 1.0 - p.y), 0.0); }
"""
    target = SHADERS.parent.parent / "gl" / "space_shaders.h"
    target.write_text("// Generated by tools/build_shaders.py from post.hlsl. Do not edit.\n#pragma once\n\nnamespace nx::gpu::shaders\n{\n"
                      "    // After kEffectGlslWords; then main() calls one of the effects.\n    inline const char kSpaceGlsl[] = R\"(\n" + start + text + ")\";\n}\n", newline="\n")
    print("wrote", target)
    hlsl3_space()


