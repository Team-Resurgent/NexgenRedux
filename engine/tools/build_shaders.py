#!/usr/bin/env python3
"""Compiles the Direct3D 11 shaders with fxc (in the Windows SDK) into one C++ header.

The header is checked in, so building the engine doesn't need this.

    python engine/tools/build_shaders.py
"""
import pathlib
import shutil
import subprocess
import tempfile

SHADERS = pathlib.Path(__file__).resolve().parent.parent / "gpu" / "d3d11" / "shaders"
SOURCE = SHADERS / "basic.hlsl"
# Shader model 4.0 runs on feature level 10_0 and up.
STAGES = [("basicVs", "vsMain", "vs_4_0"), ("basicPs", "psMain", "ps_4_0")]


def find_fxc():
    found = shutil.which("fxc")
    if found:
        return found
    kits = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\bin")
    options = sorted(kits.glob("10.*/x64/fxc.exe"))
    if not options:
        raise SystemExit("fxc not found: install the Windows SDK")
    return str(options[-1])


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return f"inline constexpr unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    fxc = find_fxc()
    out = ["// Generated by tools/build_shaders.py from basic.hlsl. Do not edit.", "#pragma once", "",
           "namespace nx::gpu::shaders", "{"]
    with tempfile.TemporaryDirectory() as tmp:
        for name, entry, profile in STAGES:
            binary = pathlib.Path(tmp) / (name + ".cso")
            subprocess.run([fxc, "/nologo", "/T", profile, "/E", entry, "/O3", "/WX", "/Qstrip_debug",
                            "/Qstrip_reflect", "/Fo", str(binary), str(SOURCE)], check=True)
            out.append(array(name, binary.read_bytes()))
    out.append("}")
    (SHADERS / "basic_shaders.h").write_text("\n".join(out) + "\n", newline="\n")
    print("wrote", SHADERS / "basic_shaders.h")


if __name__ == "__main__":
    main()
